import pytest

from presidio_ko import KrAddressRecognizer, korean_mask

recognizer = KrAddressRecognizer()


def found(text):
    return [
        (text[r.start : r.end], r.score)
        for r in recognizer.analyze(text, ["KR_ADDRESS"])
    ]


